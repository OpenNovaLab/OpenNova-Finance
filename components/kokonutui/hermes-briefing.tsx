"use client"

import { cn } from "@/lib/utils"
import { Bot, History } from "lucide-react"
import { useEffect, useState, type ReactNode } from "react"
import { loadSettingsSnapshot } from "@/lib/settings-store"

interface HermesBriefingProps {
  className?: string
}

interface BriefingItem {
  id: string
  date: string
  source: "hermes" | "nova"
  titre: string
  contenuMarkdown: string
  recuLe: string
  metadonnees?: {
    source?: string
    modele?: string
    genereLe?: string
    symboles?: string[]
  }
}

interface BriefingsResponse {
  ok: boolean
  enabled?: boolean
  latest: BriefingItem | null
  history: BriefingItem[]
}

/**
 * Hébergement hybride : la section n'est active que sur l'instance
 * locale (NEXT_PUBLIC_HERMES_ENABLED=true, définie avant le build).
 * Sur la copie Vercel, elle affiche un état clair « instance locale
 * seulement » et ne fait aucun appel réseau.
 */
const HERMES_UI_ENABLED = process.env.NEXT_PUBLIC_HERMES_ENABLED === "true"

/** Rendu gras **texte** uniquement — aucun HTML brut n'est interprété. */
function renderInline(text: string): ReactNode {
  const parts = text.split(/\*\*([^*]+)\*\*/)
  return parts.map((part, index) =>
    index % 2 === 1 ? (
      <strong key={index} className="font-semibold text-foreground">
        {part}
      </strong>
    ) : (
      <span key={index}>{part}</span>
    )
  )
}

/**
 * Mini-rendu Markdown volontairement borné : titres (#, ##, ###), listes
 * à puces (-, *, •) et paragraphes. Le contenu vient du pont local de
 * confiance, mais il est tout de même rendu en texte structuré, jamais
 * en HTML injecté.
 */
function MarkdownContent({ content }: { content: string }) {
  const blocks: ReactNode[] = []
  const lines = content.split(/\r?\n/)
  let paragraph: string[] = []
  let list: string[] = []

  const flushParagraph = (key: string) => {
    if (paragraph.length > 0) {
      blocks.push(
        <p key={key} className="text-sm leading-relaxed text-muted-foreground">
          {renderInline(paragraph.join(" "))}
        </p>
      )
      paragraph = []
    }
  }
  const flushList = (key: string) => {
    if (list.length > 0) {
      blocks.push(
        <ul key={key} className="list-disc space-y-1 pl-5">
          {list.map((item, index) => (
            <li key={index} className="text-sm leading-relaxed text-muted-foreground">
              {renderInline(item)}
            </li>
          ))}
        </ul>
      )
      list = []
    }
  }

  lines.forEach((rawLine, index) => {
    const line = rawLine.trim()
    const key = `b-${index}`
    if (line.length === 0) {
      flushParagraph(`${key}-p`)
      flushList(`${key}-l`)
      return
    }
    const heading = line.match(/^(#{1,3})\s+(.*)$/)
    if (heading) {
      flushParagraph(`${key}-p`)
      flushList(`${key}-l`)
      blocks.push(
        <h4 key={key} className="pt-1 text-sm font-semibold tracking-tight text-foreground">
          {renderInline(heading[2])}
        </h4>
      )
      return
    }
    const bullet = line.match(/^[-*•]\s+(.*)$/)
    if (bullet) {
      flushParagraph(`${key}-p`)
      list.push(bullet[1])
      return
    }
    flushList(`${key}-l`)
    paragraph.push(line)
  })
  flushParagraph("end-p")
  flushList("end-l")

  return <div className="space-y-2">{blocks}</div>
}

export default function HermesBriefing({ className }: HermesBriefingProps) {
  const [uiLocale, setUiLocale] = useState<"fr" | "en">("fr")
  const [data, setData] = useState<BriefingsResponse | null>(null)
  const [selectedId, setSelectedId] = useState<string | null>(null)

  useEffect(() => {
    const syncLocale = () => {
      const snapshot = loadSettingsSnapshot()
      setUiLocale(snapshot.language === "en" ? "en" : "fr")
    }
    syncLocale()
    const intervalId = window.setInterval(syncLocale, 2_500)
    return () => {
      window.clearInterval(intervalId)
    }
  }, [])

  useEffect(() => {
    if (!HERMES_UI_ENABLED) return
    let active = true
    const load = async () => {
      try {
        const response = await fetch("/api/hermes/briefings", { cache: "no-store" })
        if (!response.ok) throw new Error("load_failed")
        const payload = (await response.json()) as BriefingsResponse
        if (active) setData(payload)
      } catch {
        if (active) setData({ ok: false, latest: null, history: [] })
      }
    }
    void load()
    const intervalId = window.setInterval(() => {
      void load()
    }, 60_000)
    return () => {
      active = false
      window.clearInterval(intervalId)
    }
  }, [])

  const copy =
    uiLocale === "en"
      ? {
          empty: "No briefing received yet — neither Hermes (local) nor Nova has published one.",
          receivedAt: "Received",
          history: "Recent briefings",
          generatedBy: "Generated by",
          loading: "Loading the latest briefing…",
          localOnly:
            "The Hermes briefing is available on the local instance only (on Alex's PC, next to Hermes).",
        }
      : {
          empty: "Aucun briefing reçu — ni Hermes (local) ni Nova n'ont encore publié.",
          receivedAt: "Reçu le",
          history: "Briefings récents",
          generatedBy: "Généré par",
          loading: "Chargement du dernier briefing…",
          localOnly:
            "Le briefing Hermes est disponible sur l'instance locale seulement (sur le PC d'Alex, à côté de Hermes).",
        }

  const history = data?.history ?? []
  const selected =
    history.find((briefing) => briefing.id === selectedId) ?? data?.latest ?? null
  const dateLocale = uiLocale === "en" ? "en-US" : "fr-FR"

  return (
    <div className={cn("w-full", "fx-panel", "flex flex-col", className)}>
      <div className="space-y-4 p-4">
        {!HERMES_UI_ENABLED || data?.enabled === false ? (
          <div className="flex items-start gap-2">
            <Bot className="mt-0.5 h-4 w-4 shrink-0 text-muted-foreground" />
            <p className="text-sm text-muted-foreground">{copy.localOnly}</p>
          </div>
        ) : data === null ? (
          <p className="text-xs text-muted-foreground">{copy.loading}</p>
        ) : selected === null ? (
          <div className="flex items-start gap-2">
            <Bot className="mt-0.5 h-4 w-4 shrink-0 text-muted-foreground" />
            <p className="text-sm text-muted-foreground">{copy.empty}</p>
          </div>
        ) : (
          <>
            <div className="space-y-1">
              <div className="flex flex-wrap items-center gap-2">
                <Bot className="h-4 w-4 text-primary" />
                <h3 className="text-sm font-semibold tracking-tight text-foreground">
                  {selected.titre}
                </h3>
                <span className="rounded-full border border-border/60 bg-accent/50 px-2 py-0.5 text-[11px] font-semibold text-muted-foreground">
                  {selected.date}
                </span>
                <span
                  className={cn(
                    "rounded-full border px-2 py-0.5 text-[11px] font-semibold uppercase",
                    selected.source === "nova"
                      ? "border-primary/50 bg-primary/10 text-foreground"
                      : "border-border/60 bg-accent/50 text-muted-foreground"
                  )}
                >
                  {selected.source === "nova" ? "Nova" : "Hermes"}
                </span>
              </div>
              <p className="text-[11px] text-muted-foreground">
                {copy.receivedAt}{" "}
                {new Date(selected.recuLe).toLocaleString(dateLocale, {
                  dateStyle: "medium",
                  timeStyle: "short",
                })}
                {selected.metadonnees?.modele
                  ? ` — ${copy.generatedBy} ${selected.metadonnees.modele}`
                  : ""}
              </p>
            </div>

            <MarkdownContent content={selected.contenuMarkdown} />

            {history.length > 1 ? (
              <div className="space-y-2 border-t border-border/60 pt-3">
                <h4 className="flex items-center gap-1.5 text-xs font-semibold tracking-tight text-foreground">
                  <History className="h-3.5 w-3.5 text-primary" />
                  {copy.history}
                </h4>
                <div className="flex flex-wrap gap-2">
                  {history.map((briefing) => (
                    <button
                      key={briefing.id}
                      type="button"
                      onClick={() => setSelectedId(briefing.id)}
                      className={cn(
                        "rounded-full border px-2.5 py-1 text-[11px] font-medium transition-colors",
                        briefing.id === selected.id
                          ? "border-primary/50 bg-primary/10 text-foreground"
                          : "border-border/60 bg-background/60 text-muted-foreground hover:text-foreground"
                      )}
                    >
                      {briefing.date} — {briefing.source === "nova" ? "Nova" : "Hermes"} —{" "}
                      {briefing.titre}
                    </button>
                  ))}
                </div>
              </div>
            ) : null}
          </>
        )}
      </div>
    </div>
  )
}
